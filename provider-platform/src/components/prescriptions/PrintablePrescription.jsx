import { Image } from "@/components/ui/image";
import { medicationText } from "@/lib/medicationText";
import { formatPrescriptionDate, DEFAULT_DATE_FORMAT } from "@/lib/prescriptionDates";

export default function PrintablePrescription({ prescription, resident, items, dateFormat = DEFAULT_DATE_FORMAT }) {
  const wardBed = [prescription.ward, prescription.bed].filter(Boolean).join(" ");
  const location = [prescription.facility, wardBed ? `(${wardBed})` : ""].filter(Boolean).join(" ");
  const rxDate = formatPrescriptionDate(prescription.prescription_date, dateFormat);

  return (
    <div id="print-area" className="bg-white text-black p-8 border rounded-lg max-w-3xl mx-auto">
      <div className="flex justify-between items-start gap-8">
        <div className="border-2 border-black px-4 py-3 space-y-1 text-sm min-w-[280px]">
          <p className="font-bold uppercase">{resident ? resident.name : ""}</p>
          <p>Patient ID: __________________________</p>
          <p>Gender: {prescription.gender || "__________________________"}</p>
          <p>DOB: {prescription.date_of_birth || "__________________________"}</p>
          <p className={prescription.drug_allergy ? "font-bold" : ""}>Drug Allergy: {prescription.drug_allergy || "__________________________"}</p>
          {wardBed && <p>Level/ward: {wardBed}</p>}
        </div>
        <div className="text-right shrink-0">
          <Image src="/logo.png" alt="Facility logo" fittingType="fit" className="ml-auto mb-2 w-24 h-32" />
          <p className="font-bold text-lg leading-tight uppercase">
            {prescription.facility || "[Facility Name]"}
          </p>
          <p className="text-xs text-gray-600 mt-1">{prescription.facility_address || ""}</p>
        </div>
      </div>

      <p className="mt-8 text-sm">
        <span className="underline">Prescription Date : {rxDate}</span>
      </p>

      <table className="w-full text-sm border border-black mt-4">
        <thead>
          <tr className="border-b border-black text-left">
            <th className="px-2 py-1.5 w-10">No.</th>
            <th className="px-2 py-1.5 w-20">Route</th>
            <th className="px-2 py-1.5">Medicine Name / Dose / Unit / Form / Frequency</th>
            <th className="px-2 py-1.5 w-44">Duration / Quantity</th>
          </tr>
        </thead>
        <tbody>
          {(items || []).map((item, i) => (
            <tr key={item.id || i} className="border-b border-black last:border-0">
              <td className="px-2 py-1.5">{i + 1}.</td>
              <td className="px-2 py-1.5">{item.route || "—"}</td>
              <td className="px-2 py-1.5">
                {medicationText(item) || "—"}
              </td>
              <td className="px-2 py-1.5">
                {[item.duration, item.quantity].filter(Boolean).join(" ")} {item.uom || ""}
              </td>
            </tr>
          ))}
        </tbody>
      </table>

      <div className="flex justify-between items-end pt-16 text-sm">
        <div className="space-y-8 w-80">
          <p>Doctor's Name :</p>
          <p>MCR No :</p>
          <p className="border-t border-black pt-1">Signature</p>
          <p className="border-t border-black pt-1">Date</p>
        </div>

      </div>

      <p className="mt-6 text-[10px] text-gray-600">
        Trace ID {prescription.trace_id} · Version {prescription.version} · Copy {prescription.print_count} · Generated by
        the Nursing Home Prescription Generator — valid only upon the doctor's physical approval and signature.
      </p>
    </div>
  );
}